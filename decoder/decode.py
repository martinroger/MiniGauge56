#!/usr/bin/env python3
"""
CAN Bus Binary Log Decoder
==========================
Decodes binary CAN log files generated by the ESP32 MiniGauge firmware into:
  1. Vector ASC files (.asc) - compatible with Vector CANoe, CANalyzer, SavvyCAN, etc.
  2. Decoded CSV files (.csv) - message-by-message log with physical signal values.
  3. (Optional) Flat signals CSV (_signals.csv) - ideal for plotting time series.

Binary record layout (16 bytes, packed little-endian, from main/logging.cpp):
    uint32_t timestamp; // 4 bytes (ms uptime)
    uint16_t id;        // 2 bytes (CAN arbitration ID)
    uint8_t  dlc;       // 1 byte  (data length code, 0-8)
    uint8_t  data[8];   // 8 bytes (payload data)
    uint8_t  padding;   // 1 byte  (padding to 16 bytes)
"""

import sys
import os
import struct
import glob
import re
import json
from pathlib import Path
from datetime import datetime, timezone
import argparse
from typing import Dict, List, Optional, Tuple, Any

RECORD_STRUCT = "<IHB8sx"
RECORD_SIZE = 16


# ---------------------------------------------------------------------------
# Built-in Lightweight DBC Database
# ---------------------------------------------------------------------------
class SignalDef:
    def __init__(
        self,
        name: str,
        mux: Optional[str],
        start_bit: int,
        bit_len: int,
        is_intel: bool,
        is_signed: bool,
        factor: float,
        offset: float,
        min_val: float,
        max_val: float,
        unit: str,
        valtype: int = 0,
        choices: Optional[Dict[int, str]] = None,
    ):
        self.name = name
        self.mux = mux  # 'M' for multiplexor, 'm<N>' for multiplexed, None for standard
        self.start_bit = start_bit
        self.bit_len = bit_len
        self.is_intel = is_intel
        self.is_signed = is_signed
        self.factor = factor
        self.offset = offset
        self.min_val = min_val
        self.max_val = max_val
        self.unit = unit
        self.valtype = valtype  # 0: int, 1: float32, 2: float64
        self.choices = choices or {}

    def decode_raw(self, payload: bytes) -> int:
        """Extracts raw integer bits from payload according to byte order."""
        if self.is_intel:
            val_int = int.from_bytes(payload, "little")
            return (val_int >> self.start_bit) & ((1 << self.bit_len) - 1)
        else:
            # Motorola (Big Endian) sequential bit extraction
            val = 0
            cur_bit = self.start_bit
            for _ in range(self.bit_len):
                byte_idx = cur_bit // 8
                bit_in_byte = cur_bit % 8
                if byte_idx < len(payload):
                    bit = (payload[byte_idx] >> bit_in_byte) & 1
                else:
                    bit = 0
                val = (val << 1) | bit
                if bit_in_byte == 0:
                    cur_bit = (byte_idx + 2) * 8 - 1
                else:
                    cur_bit -= 1
            return val

    def decode(self, payload: bytes) -> Tuple[Any, Optional[str]]:
        """Decodes raw bits into physical value and optional named enum choice."""
        raw = self.decode_raw(payload)

        # Signed conversion if not float
        if self.is_signed and not self.valtype:
            if raw & (1 << (self.bit_len - 1)):
                raw -= (1 << self.bit_len)

        # Float handling
        if self.valtype == 1:  # 32-bit float
            raw_bytes = (raw & 0xFFFFFFFF).to_bytes(4, "little")
            raw_float = struct.unpack("<f", raw_bytes)[0]
            phys = raw_float * self.factor + self.offset
        elif self.valtype == 2:  # 64-bit double
            raw_bytes = (raw & 0xFFFFFFFFFFFFFFFF).to_bytes(8, "little")
            raw_double = struct.unpack("<d", raw_bytes)[0]
            phys = raw_double * self.factor + self.offset
        else:
            phys = raw * self.factor + self.offset

        # Round clean floats or preserve integer
        if isinstance(phys, float):
            if phys.is_integer():
                phys = int(phys)
            else:
                phys = round(phys, 5)

        named = self.choices.get(int(raw))
        return phys, named


class MessageDef:
    def __init__(self, msg_id: int, name: str, dlc: int, sender: str):
        self.msg_id = msg_id
        self.name = name
        self.dlc = dlc
        self.sender = sender
        self.signals: List[SignalDef] = []
        self.mux_signal: Optional[SignalDef] = None

    def add_signal(self, sig: SignalDef):
        self.signals.append(sig)
        if sig.mux == "M":
            self.mux_signal = sig

    def decode(self, payload: bytes) -> Dict[str, Dict[str, Any]]:
        # Pad payload to at least 8 bytes for bit extraction
        if len(payload) < 8:
            payload = payload.ljust(8, b"\x00")

        # Determine multiplexor value if present
        mux_val = None
        if self.mux_signal:
            mux_val = self.mux_signal.decode_raw(payload)

        results = {}
        for sig in self.signals:
            if sig.mux and sig.mux != "M":
                try:
                    expected_mux = int(sig.mux[1:])
                    if mux_val != expected_mux:
                        continue
                except ValueError:
                    pass

            phys_val, choice_name = sig.decode(payload)
            results[sig.name] = {
                "value": phys_val,
                "unit": sig.unit,
                "choice": choice_name,
            }
        return results


class DbcDatabase:
    def __init__(self, filepath: str):
        self.filepath = filepath
        self.messages: Dict[int, MessageDef] = {}
        self._parse(filepath)

    def _parse(self, filepath: str):
        with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()

        # 1. Parse SIG_VALTYPE_
        valtype_re = re.compile(
            r"^SIG_VALTYPE_\s+(\d+)\s+(\w+)\s*:\s*(\d+)\s*;", re.MULTILINE
        )
        valtypes: Dict[Tuple[int, str], int] = {}
        for m in valtype_re.finditer(content):
            valtypes[(int(m.group(1)), m.group(2))] = int(m.group(3))

        # 2. Parse VAL_ enum tables
        val_re = re.compile(r"^VAL_\s+(\d+)\s+(\w+)\s+(.+);", re.MULTILINE)
        val_entry_re = re.compile(r'(\d+)\s+"([^"]*)"')
        val_choices: Dict[Tuple[int, str], Dict[int, str]] = {}
        for m in val_re.finditer(content):
            msg_id = int(m.group(1))
            sig_name = m.group(2)
            entries = val_entry_re.findall(m.group(3))
            val_choices[(msg_id, sig_name)] = {int(k): v for k, v in entries}

        # 3. Parse BO_ and SG_
        sg_re = re.compile(
            r'SG_\s+(\w+)\s*(?:(M|m\d+))?\s*:\s*(\d+)\|(\d+)@([01])([+-])\s+\(([-0-9.eE+]+),([-0-9.eE+]+)\)\s+\[([-0-9.eE+]+)\|([-0-9.eE+]+)\]\s+\"([^\"]*)\"'
        )

        current_msg: Optional[MessageDef] = None
        for line in content.splitlines():
            stripped = line.strip()
            if line.startswith("BO_ "):
                parts = line.split()
                if len(parts) >= 5:
                    msg_id = int(parts[1])
                    name = parts[2].rstrip(":")
                    dlc = int(parts[3])
                    sender = parts[4]
                    current_msg = MessageDef(msg_id, name, dlc, sender)
                    self.messages[msg_id] = current_msg
            elif stripped.startswith("SG_ ") and current_msg is not None:
                m = sg_re.search(stripped)
                if m:
                    sig_name = m.group(1)
                    mux = m.group(2)
                    start_bit = int(m.group(3))
                    bit_len = int(m.group(4))
                    is_intel = m.group(5) == "1"
                    is_signed = m.group(6) == "-"
                    factor = float(m.group(7))
                    offset = float(m.group(8))
                    min_val = float(m.group(9))
                    max_val = float(m.group(10))
                    unit = m.group(11)

                    valtype = valtypes.get((current_msg.msg_id, sig_name), 0)
                    choices = val_choices.get((current_msg.msg_id, sig_name), {})

                    sig = SignalDef(
                        name=sig_name,
                        mux=mux,
                        start_bit=start_bit,
                        bit_len=bit_len,
                        is_intel=is_intel,
                        is_signed=is_signed,
                        factor=factor,
                        offset=offset,
                        min_val=min_val,
                        max_val=max_val,
                        unit=unit,
                        valtype=valtype,
                        choices=choices,
                    )
                    current_msg.add_signal(sig)

    def get_message(self, msg_id: int) -> Optional[MessageDef]:
        return self.messages.get(msg_id)


# ---------------------------------------------------------------------------
# Binary Log Reader
# ---------------------------------------------------------------------------
class CanFrame:
    def __init__(
        self,
        timestamp_ms: int,
        time_rel_s: float,
        can_id: int,
        dlc: int,
        data: bytes,
    ):
        self.timestamp_ms = timestamp_ms
        self.time_rel_s = time_rel_s
        self.can_id = can_id
        self.dlc = dlc
        self.data = data


def read_bin_file(filepath: Path) -> List[CanFrame]:
    """Reads and parses a 16-byte packed binary log file."""
    with open(filepath, "rb") as f:
        raw_data = f.read()

    file_len = len(raw_data)
    if file_len == 0:
        return []

    record_count = file_len // RECORD_SIZE
    trailing = file_len % RECORD_SIZE
    if trailing != 0:
        print(f"  [!] Warning: {filepath.name} has {trailing} trailing bytes ignored")

    frames: List[CanFrame] = []
    first_ts: Optional[int] = None

    for i in range(record_count):
        chunk = raw_data[i * RECORD_SIZE : (i + 1) * RECORD_SIZE]
        ts_ms, can_id, dlc, payload = struct.unpack(RECORD_STRUCT, chunk)

        if first_ts is None:
            first_ts = ts_ms

        time_rel_s = max(0.0, (ts_ms - first_ts) / 1000.0)
        actual_len = min(dlc, 8)
        actual_data = payload[:actual_len]

        frames.append(CanFrame(ts_ms, time_rel_s, can_id, dlc, actual_data))

    return frames


